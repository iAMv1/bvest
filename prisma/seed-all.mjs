async function main() {
  console.log("Seeding societies...");
  for (const s of SOCIETIES) {
    const hashed = await bcrypt.hash(s.password, 12);
    await prisma.society.upsert({
      where: { id: s.id },
      update: {},
      create: { id: s.id, name: s.name, password: hashed, locked: false, kind: s.kind },
    });
  }

  console.log("Seeding events...");
  for (const ev of EVENTS) {
    await prisma.event.upsert({
      where: { slug: ev.slug },
      update: {
        title: ev.title,
        description: ev.description,
        startDate: ev.startDate,
        endDate: ev.endDate,
        venue: ev.venue,
        registrationUrl: ev.registrationUrl,
        sdgDomainId: ev.sdgDomainId,
        status: ev.status,
        hostSocietyId: ev.hostSocietyId,
      },
      create: {
        title: ev.title,
        slug: ev.slug,
        description: ev.description,
        startDate: ev.startDate,
        endDate: ev.endDate,
        venue: ev.venue,
        registrationUrl: ev.registrationUrl,
        sdgDomainId: ev.sdgDomainId,
        status: ev.status,
        hostSocietyId: ev.hostSocietyId,
      },
    });
    console.log(`✓ Seeded event: ${ev.title} (${ev.slug})`);
  }

  console.log("All events successfully seeded!");
}

main().catch(console.error).finally(() => prisma.$disconnect());

